type TranslationNode = Record<string, unknown>;

function isCorruptedText(value: string): boolean {
  return value.includes('пїЅ') || value.includes('�');
}

function restoreLocaleFromFallback(target: TranslationNode, fallback: TranslationNode): void {
  for (const key of Object.keys(target)) {
    const targetValue = target[key];
    const fallbackValue = fallback[key];

    if (typeof targetValue === 'string' && typeof fallbackValue === 'string') {
      if (isCorruptedText(targetValue)) {
        target[key] = fallbackValue;
      }
      continue;
    }

    if (
      targetValue &&
      fallbackValue &&
      typeof targetValue === 'object' &&
      typeof fallbackValue === 'object' &&
      !Array.isArray(targetValue) &&
      !Array.isArray(fallbackValue)
    ) {
      restoreLocaleFromFallback(targetValue as TranslationNode, fallbackValue as TranslationNode);
    }
  }
}

restoreLocaleFromFallback(translations.ua as TranslationNode, translations.en as TranslationNode);
restoreLocaleFromFallback(translations.ru as TranslationNode, translations.en as TranslationNode);
export type Language = 'ua' | 'ru' | 'en';
export type TranslationKey = keyof typeof translations.ua;
