    add_bold_paragraph(document, "Базові припущення для розрахунку")
    assumptions = [
        "Розрахунок базується на 50 потенційних партнерів: 10 шкіл, 10 садочків, 10 салонів і 20 локальних сервісів / бізнесів.",
        "Середня базова підписка: 500 грн/місяць за присутність у каталозі, акції, новини, пріоритет у видачі та комунікацію з жителями.",
        "AI, сервіси, Firebase, реклама та інші технічні інструменти варто рахувати як операційні витрати, а не як окрему частку прибутку.",
        "Для локального бізнесу модель 500 грн/місяць виглядає адекватно, якщо додаток дає хоча б 1 нового клієнта або 3-5 цільових звернень на місяць.",
    ]
    for assumption in assumptions:
        document.add_paragraph(f"- {assumption}")

    add_bold_paragraph(document, "Сценарії доходу")
    scenario_rows = [
        [
            "Сценарій",
            "Кількість платних партнерів",
            "Валовий дохід / міс",
            "Операційні витрати / міс",
            "Чистий залишок / міс",
        ],
        ["Консервативний", "10", "5 000 грн", "2 500-3 500 грн", "1 500-2 500 грн"],
        ["Робочий", "25", "12 500 грн", "4 000-6 000 грн", "6 500-8 500 грн"],
        ["Цільовий", "50", "25 000 грн", "6 000-9 000 грн", "16 000-19 000 грн"],
        ["Сильний", "80", "40 000 грн", "9 000-13 000 грн", "27 000-31 000 грн"],
    ]
    scenario_table = document.add_table(rows=len(scenario_rows), cols=len(scenario_rows[0]))
    fill_table(scenario_table, scenario_rows)

    document.add_paragraph(
        "Отже, модель з 50 платними партнерами по 500 грн/місяць дає 25 000 грн валового "
        "доходу на місяць або близько 300 000 грн на рік до витрат. Але для перших 3-6 "
        "місяців після запуску реалістичніше планувати 10-25 платних партнерів, а не "
        "відразу 50."
    )

    add_bold_paragraph(document, "Рекомендований принцип розподілу чистого залишку")
    distribution = [
        "Викрам - 40%: технічна розробка, PM, релізи, стабільність, аналітика, координація.",
        "Оксана - 35%: продажі, маркетинг, переговори з бізнесами, упаковка та контент.",
        "Марина - 10%: анонси, охоплення Facebook-групи, регулярні промо-розміщення.",
        "Резерв проекту - 15%: реклама, підтримка, контент, юрист, Firebase Blaze, непередбачені витрати.",
        "AI / інструменти - окрема стаття витрат орієнтовно 1 000-3 000 грн/місяць, а не частка прибутку.",
    ]
